#!/usr/bin/env node

/**
 * rss1102/chore/generate-declarations
 *
 * Post-build script: restructure tsc-generated .d.ts files to match
 * the Rollup bundle's flat output structure.
 *
 * Problem:
 *   - Rollup outputs: lib/chat-engine/index.js, lib/chat-message/index.js, ...
 *   - tsc outputs:     lib/common-utils/_ai-core/packages/chat-engine/index.d.ts, ...
 *   (because tsconfig paths resolve aliases to real file paths)
 *
 * This script reads each Rollup-generated index.js, extracts its exports,
 * and creates matching index.d.ts stubs that re-export from the actual
 * tsc declaration locations.
 *
 * Usage:
 *   node packages/script/generate-declarations.mjs
 *   (called automatically after build:tsc-lib)
 */

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
// This script lives at packages/script/, so ROOT is two levels up (project root)
const ROOT = join(__dirname, '..', '..');
const LIB_DIR = join(ROOT, 'packages/chat/lib');

// Sub-module directories that Rollup outputs to lib/
const SUB_MODULES = [
  'chat-sender', 'chatbot', 'chat-message', 'chat-loading',
  'chat-action', 'attachments', 'filecard', 'chat-engine',
];

// Content sub-directories within chat-message
const CONTENT_DIRS = [
  'markdown-content', 'reasoning-content', 'search-content',
  'thinking-content', 'suggestion-content',
];

// External packages whose types are provided by link-submodule via sibling dir
// Path from lib/<sub-module>/ to the type declarations:
//   lib/chat-engine/index.d.ts → ../../../../@tdesign/ai-chat-engine/packages/chat-engine/dist
const EXTERNAL_TYPE_REWRITE = {
  '@tdesign/ai-chat-engine': '../../../../@tdesign/ai-chat-engine/packages/chat-engine/dist',
};

/**
 * Parse a JS entry file and extract export statements.
 * Rewrites external package refs to relative paths for self-contained .d.ts.
 */
function parseJsExports(jsContent) {
  const lines = [];
  for (const line of jsContent.split('\n')) {
    const t = line.trim();
    if (!t || t.startsWith('//') || t.startsWith('/*') || t.startsWith('*')) continue;

    // export { X, Y as Z };
    if (t.startsWith('export {') && t.endsWith('};')) {
      lines.push(t);
    }
    // export * from '...';
    else if (t.startsWith("export * from")) {
      const match = t.match(/export \* from ['"]([^'"]+)['"]/);
      if (match) {
        const src = match[1];
        const rewritten = EXTERNAL_TYPE_REWRITE[src] || src;
        lines.push(`export * from '${rewritten}';`);
        lines.push(`export type * from '${rewritten}';`);
      } else {
        lines.push(t);
      }
    }
    // export { ... } from '...';
    else if (/^export\s+\{.*\}\s*from\s+/.test(t)) {
      const match = t.match(/export\s+\{(.*?)\}\s*from\s+['"]([^'"]+)['"]/);
      if (match) {
        const [, exports, src] = match;
        const rewritten = EXTERNAL_TYPE_REWRITE[src] || src;
        lines.push(`export { ${exports} } from '${rewritten}';`);
      } else {
        lines.push(t);
      }
    }
    // export default ...
    else if (t.startsWith('export default')) {
      // Skip default value exports in dts
    }
    // import statements — skip
    else if (t.startsWith('import ')) {
      // skip
    }
  }
  return lines;
}

/**
 * Generate an index.d.ts for a sub-module by reading its index.js.
 */
function generateSubModuleDts(modDir) {
  const indexPath = join(modDir, 'index.js');
  if (!existsSync(indexPath)) return false;

  const jsContent = readFileSync(indexPath, 'utf-8');
  const exports = parseJsExports(jsContent);

  if (exports.length === 0) return false;

  const dtsLines = ['/** Auto-generated by generate-declarations.mjs */', '', ...exports, ''];
  writeFileSync(join(modDir, 'index.d.ts'), dtsLines.join('\n'));
  return true;
}

// --- Main ---

console.log('[generate-declarations] Restructuring type declarations...\n');

let generated = 0;

// 1. Generate root lib/index.d.ts — re-exports all sub-modules
const rootExports = SUB_MODULES.flatMap((mod) => [
  `export * from './${mod}';`,
  `export type * from './${mod}';`,
]);
writeFileSync(
  join(LIB_DIR, 'index.d.ts'),
  [
    '/** Auto-generated by generate-declarations.mjs */',
    '',
    ...rootExports,
    // Also expose types from source-level declarations (TdXxxProps etc)
    "export type * from './packages/chat/src/index';",
    '',
  ].join('\n'),
);
generated += 1;
console.log(`  + lib/index.d.ts (${SUB_MODULES.length} sub-modules)`);

// 2. Generate each sub-module's index.d.ts
for (const mod of SUB_MODULES) {
  const modDir = join(LIB_DIR, mod);
  if (generateSubModuleDts(modDir)) {
    generated += 1;
    console.log(`  + lib/${mod}/index.d.ts`);
  }

  // Also handle content sub-dirs inside chat-message
  if (mod === 'chat-message') {
    for (const content of CONTENT_DIRS) {
      const contentDir = join(modDir, 'content', content);
      if (generateSubModuleDts(contentDir)) {
        generated += 1;
        console.log(`  + lib/${mod}/content/${content}/index.d.ts`);
      }
    }
  }
}

console.log(`\n[generate-declarations] Done! Generated ${generated} declaration files.\n`);
